/** Slug traducido de una sección canónica (es) para el idioma dado; cae al slug español si falta. */
export function slugParaIdioma(seccionCanonica, lang) {
	return SLUGS[lang]?.[seccionCanonica] ?? seccionCanonica;
}

/** Idioma + slug traducido -> sección canónica (es), o null si no coincide con ninguna. */
export function seccionCanonicaDesdeSlug(lang, slug) {
	const mapa = SLUGS[lang];
	if (!mapa) return null;
	const entrada = Object.entries(mapa).find(([, valor]) => valor === slug);
	return entrada ? entrada[0] : null;
}
